"""Minimal ELF dependency inspection and selective runtime-library staging.

Only the executable's direct ELF dependency closure is copied from fixed,
read-only system library locations.  The host filesystem is never mounted as
a whole.  The extracted AppDir remains the application payload and is mounted
read-only at ``/opt/app`` by :mod:`appsbx.runtime`.
"""


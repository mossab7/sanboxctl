def _within(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def _read_cstring(data: bytes, offset: int) -> str:
    if offset < 0 or offset >= len(data):
        raise ELFError("ELF string-table offset is invalid")
    end = data.find(b"\0", offset)
    if end < 0:
        raise ELFError("ELF string-table entry is unterminated")
    try:
        return data[offset:end].decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ELFError("ELF string-table entry is not UTF-8") from exc


def _vaddr_to_offset(load_segments: list[tuple[int, int, int]], address: int) -> int:
    for vaddr, file_offset, file_size in load_segments:
        if vaddr <= address < vaddr + file_size:
            return file_offset + (address - vaddr)
    raise ELFError("ELF virtual address is outside a load segment")


def read_elf_info(path: Path) -> ELFInfo:
    try:
        with path.open("rb") as handle:
            ident = handle.read(16)
            if ident[:4] != b"\x7fELF" or ident[5] != 1 or ident[4] not in (1, 2):
                raise ELFError(f"unsupported ELF file: {path.name}")
            is_64 = ident[4] == 2
            if is_64:
                header_format = "<HHIQQQIHHHHHH"
                header_size = struct.calcsize(header_format)
                header = struct.unpack(header_format, handle.read(header_size))
                phoff, phentsize, phnum = header[4], header[8], header[9]
                ph_format = "<IIQQQQQQ"
            else:
                header_format = "<HHIIIIIHHHHHH"
                header_size = struct.calcsize(header_format)
                header = struct.unpack(header_format, handle.read(header_size))
                phoff, phentsize, phnum = header[4], header[8], header[9]
                ph_format = "<IIIIIIII"
            ph_size = struct.calcsize(ph_format)
            if phentsize < ph_size or phnum > 4096:
                raise ELFError(f"invalid ELF program-header table: {path.name}")

            load_segments: list[tuple[int, int, int]] = []
            dynamic: tuple[int, int] | None = None
            interpreter: str | None = None
            for index in range(phnum):
                handle.seek(phoff + index * phentsize)
                values = struct.unpack(ph_format, handle.read(ph_size))
                if is_64:
                    p_type, _flags, p_offset, p_vaddr, _paddr, p_filesz, _memsz, _align = values
                else:
                    p_type, p_offset, p_vaddr, _paddr, p_filesz, _memsz, _flags, _align = values
                if p_type == PT_LOAD:
                    load_segments.append((p_vaddr, p_offset, p_filesz))
                elif p_type == PT_DYNAMIC:
                    dynamic = (p_offset, p_filesz)
                elif p_type == PT_INTERP:
                    handle.seek(p_offset)
                    raw = handle.read(p_filesz)
                    interpreter = raw.split(b"\0", 1)[0].decode("utf-8")

            if dynamic is None:
                return ELFInfo(path, interpreter, (), ())
            dynamic_offset, dynamic_size = dynamic
            entry_format = "<QQ" if is_64 else "<II"
            entry_size = struct.calcsize(entry_format)
            entries: list[tuple[int, int]] = []
            for position in range(0, dynamic_size - entry_size + 1, entry_size):
                handle.seek(dynamic_offset + position)
                tag, value = struct.unpack(entry_format, handle.read(entry_size))
                if tag == DT_NULL:
                    break
                entries.append((tag, value))

            strtab_value = next((value for tag, value in entries if tag == DT_STRTAB), None)
            strsz = next((value for tag, value in entries if tag == DT_STRSZ), None)
            if strtab_value is None or strsz is None or strsz > 16 * 1024 * 1024:
                return ELFInfo(path, interpreter, (), ())
            strtab_offset = _vaddr_to_offset(load_segments, strtab_value)
            handle.seek(strtab_offset)
            strings = handle.read(strsz)

            def string_at(value: int) -> str:
                return _read_cstring(strings, value)

            needed = tuple(string_at(value) for tag, value in entries if tag == DT_NEEDED)
            search_paths = tuple(string_at(value) for tag, value in entries if tag in (DT_RPATH, DT_RUNPATH))
            return ELFInfo(path, interpreter, needed, search_paths)
    except (OSError, struct.error, UnicodeDecodeError) as exc:
        raise ELFError(f"cannot inspect ELF file: {path.name}") from exc


def _system_search_paths() -> tuple[Path, ...]:
    multiarch = sysconfig.get_config_var("MULTIARCH")
    paths = list(SYSTEM_LIBRARY_ROOTS)
    if multiarch:
        paths.extend(Path(base) / str(multiarch) for base in ("/lib", "/usr/lib"))
    if platform.machine() == "x86_64":
        paths.extend((Path("/lib/x86_64-linux-gnu"), Path("/usr/lib/x86_64-linux-gnu")))
    unique: list[Path] = []
    for path in paths:
        if path not in unique:
            unique.append(path)
    return tuple(unique)


def _candidate_source(candidate: Path, payload_roots: Iterable[Path]) -> tuple[Path, bool] | None:
    candidate = candidate.absolute()
    try:
        resolved = candidate.resolve(strict=True)
    except OSError:
        return None
    if not resolved.is_file():
        return None
    for payload_root in payload_roots:
        if _within(candidate, payload_root):
            # A payload symlink that escapes into the host is not accepted.
            if _within(resolved, payload_root):
                return candidate, True
            return None
    if any(_within(resolved, root) for root in _system_search_paths()):
        # Preserve the lexical library name so a symlink such as libc.so.6 is
        # present at the exact path the dynamic loader will open.
        return candidate, False
    return None


def _resolve_dependency(
    name: str,
    requester: Path,
    payload_roots: Iterable[Path],
    search_paths: Iterable[str],
) -> tuple[Path, bool] | None:
    payload_roots = tuple(root.resolve() for root in payload_roots)
    if not payload_roots:
        raise ELFError("dependency resolution requires a payload root")
    app_root = payload_roots[0]
    candidates: list[Path] = []
    if name.startswith("/"):
        candidates.append(app_root / name.lstrip("/"))
        candidates.append(Path(name))
    origin = requester.parent
    for raw_path in search_paths:
        expanded = raw_path.replace("$ORIGIN", str(origin)).replace("${ORIGIN}", str(origin))
        path = Path(expanded)
        if not path.is_absolute():
            path = origin / path
        candidates.append(path / name)
    candidates.extend((
        app_root / name,
        app_root / "lib" / name,
        app_root / "usr" / "lib" / name,
        app_root / "usr" / "lib" / str(sysconfig.get_config_var("MULTIARCH") or "") / name,
    ))
    if not any(_within(requester, root) for root in payload_roots):
        candidates.append(requester.parent / name)
    candidates.extend(base / name for base in _system_search_paths())
    seen: set[Path] = set()
    for candidate in candidates:
        candidate = candidate.absolute()
        if candidate in seen:
            continue
        seen.add(candidate)
        source = _candidate_source(candidate, payload_roots)
        if source is not None:
            return source
    return None


def _entrypoint(app_root: Path, app_command: Iterable[str]) -> Path:
    command = list(app_command)
    if not command or not command[0].startswith("/opt/app/"):
        raise ELFError("application command must start with /opt/app/")
    relative = command[0][len("/opt/app/"):]
    if not relative or relative.startswith("/") or ".." in Path(relative).parts:
        raise ELFError("application command escapes /opt/app")
    path = (app_root / relative).resolve()
    if not _within(path, app_root.resolve()) or not path.is_file():
        raise ELFError("application executable is missing from the extracted AppDir")
    if not os.access(path, os.X_OK):
        raise ELFError("application executable is not executable")
    return path


def _downloaded_game_entrypoint(state_dir: Path, shared_game_root: Path | None = None) -> tuple[Path, str] | None:
    """Return the known Zaap Linux child executable if it is safely present.

    Zaap updates this Electron child below its already-private HOME. It is not
    mounted as a new host path; it is only used to stage its declared system
    ELF closure into the private runtime bundle.
    """
    game_root = shared_game_root if shared_game_root is not None else state_dir / "home" / ".config" / "Ankama" / "Retro"
    entrypoint = game_root / "dofus1electron"
    try:
        root = game_root.resolve(strict=True)
        entrypoint = entrypoint.resolve(strict=True)
        info = entrypoint.stat(follow_symlinks=False)
    except OSError:
        return None
    # A private game must live below this profile's state.  The managed shared
    # snapshot intentionally lives outside it, but is later separately
    # validated and mounted read-only by ``prepare_plan``.  Treating that
    # snapshot as private here prevented its ELF closure from being staged,
    # leaving Dofus without system libraries such as librt.so.1.
    if (
        (shared_game_root is None and not _within(root, state_dir.resolve()))
        or (shared_game_root is not None and root != shared_game_root.resolve())
        or not _within(entrypoint, root)
        or entrypoint.is_symlink()
        or not entrypoint.is_file()
        or not os.access(entrypoint, os.X_OK)
    ):
        return None
    return entrypoint, f"{info.st_size:x}-{info.st_mtime_ns:x}"


def _stage_host_path(
    source: Path,
    bundle_root: Path,
    staged: set[Path],
    allowed_roots: tuple[Path, ...] = SYSTEM_LIBRARY_ROOTS,
) -> None:
    source = source.absolute()
    if source in staged:
        return
    staged.add(source)
    destination = bundle_root / source.relative_to("/")
    destination.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
    if source.is_symlink():
        target = os.readlink(source)
        if not destination.exists() and not destination.is_symlink():
            destination.symlink_to(target)
        resolved = source.resolve(strict=True)
        if not any(_within(resolved, root) for root in allowed_roots):
            raise ELFError("staged symlink leaves approved system roots")
        # A host such as Debian may have /lib as a symlink into /usr/lib.
        # Preserve the target at the lexical /lib path too, because /lib and
        # /usr are mounted as separate read-only trees inside the sandbox.
        lexical_target = Path(target) if os.path.isabs(target) else source.parent / target
        _stage_host_path(lexical_target, bundle_root, staged, allowed_roots)
        _stage_host_path(resolved, bundle_root, staged, allowed_roots)
    else:
        if not source.is_file():
            raise ELFError("ELF dependency is not a regular file")
        if not destination.exists():
            shutil.copy2(source, destination)


def _stage_regular_file(
    source: Path,
    bundle_root: Path,
    allowed_roots: tuple[Path, ...],
) -> None:
    """Stage one fixed data file without preserving an escaping symlink.

    Some distributions install ``/usr/share/locale/locale.alias`` as a
    symlink into ``/etc``.  The sandbox deliberately does not mount a generic
    host ``/etc`` tree, so preserving that symlink would leave the resource
    unavailable.  Copying the approved target as a regular file keeps the
    resource self-contained and does not expose host identity files.
    """
    source = source.absolute()
    try:
        resolved = source.resolve(strict=True)
    except OSError as exc:
        raise ELFError(f"required runtime data is unavailable: {source}") from exc
    if not resolved.is_file() or not any(_within(resolved, root) for root in allowed_roots):
        raise ELFError(f"runtime data is outside approved system roots: {source}")
    destination = bundle_root / source.relative_to("/")
    destination.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
    shutil.copy2(resolved, destination)


def _write_private_xdg_settings(bundle_root: Path) -> Path:
    """Provide the protocol-registration helper inside the sandbox only.

    Electron 16 invokes xdg-settings during ``setAsDefaultProtocolClient``.
    A desktop-handler registration is intentionally not allowed to modify the
    host desktop or contact a host D-Bus session, so this private helper
    acknowledges the request and performs no external action.  It is placed
    in the staged /usr tree and is never installed on the host.
    """
    path = bundle_root / "usr" / "bin" / "xdg-settings"
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
    path.write_text(
        "#!/bin/sh\n"
        "# appsbx: desktop protocol registration is intentionally private/no-op.\n"
        "exit 0\n",
        encoding="utf-8",
    )
    os.chmod(path, 0o755)
    return path


def _private_browser_source() -> Path:
    """Return the fixed browser payload used by the private URL broker.

    The caller stages this package tree into the per-profile runtime.  It is
    never bind-mounted from ``/opt`` and it never receives a host browser
    profile, desktop service, or host network namespace.
    """
    try:
        root = GOOGLE_CHROME_ROOT.resolve(strict=True)
        executable = GOOGLE_CHROME_EXECUTABLE.resolve(strict=True)
    except OSError as exc:
        raise ELFError(
            "private URL broker requires Google Chrome at /opt/google/chrome; "
            "install it separately or use --url-broker off"
        ) from exc
    if (
        root != GOOGLE_CHROME_ROOT
        or not root.is_dir()
        or not _within(executable, root)
        or not executable.is_file()
        or not os.access(executable, os.X_OK)
    ):
        raise ELFError("private URL broker browser payload is invalid")
    return executable


def _write_private_xdg_open(bundle_root: Path, browser: Path) -> Path:
    """Write a narrow in-sandbox replacement for ``xdg-open``.

    Only one HTTP(S) URL is accepted.  File, data, JavaScript, arbitrary
    custom schemes, option-like arguments, and host desktop dispatch are
    rejected.  The launched browser stores state only below the already
    private profile HOME and inherits the application namespace and selected
    egress policy.
    """
    browser_path = "/" + str(browser.resolve().relative_to("/"))
    path = bundle_root / "usr" / "bin" / "xdg-open"
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
    path.write_text(
        "#!/bin/sh\n"
        "# appsbx private URL broker; never delegates to the host desktop.\n"
        "set -eu\n"
        "if [ \"$#\" -ne 1 ]; then\n"
        "  echo 'appsbx xdg-open: exactly one HTTP(S) URL is required' >&2\n"
        "  exit 64\n"
        "fi\n"
        "url=$1\n"
        "case \"$url\" in\n"
        "  http://*|https://*) ;;\n"
        "  *) echo 'appsbx xdg-open: blocked non-web URL' >&2; exit 64 ;;\n"
        "esac\n"
        "authority=${url#*://}\n"
        "case \"$authority\" in\n"
        "  ''|/*|*[[:space:]]*|*\\\\*)\n"
        "    echo 'appsbx xdg-open: blocked malformed URL' >&2; exit 64 ;;\n"
        "esac\n"
        "umask 077\n"
        "broker_home=\"$HOME/.local/share/appsbx-url-browser\"\n"
        "mkdir -p \"$broker_home\"\n"
        # Chrome's setuid sandbox cannot be used from an unprivileged
        # Bubblewrap user namespace because its staged file is deliberately
        # not host-root-owned.  Do not use --no-sandbox: the outer Bubblewrap
        # mount/user/PID/IPC/UTS/cgroup/network boundary remains mandatory.
        f"\"{browser_path}\" --disable-setuid-sandbox --no-first-run "
        "--no-default-browser-check --disable-background-mode --password-store=basic "
        "--user-data-dir=\"$broker_home\" -- \"$url\" "
        ">/tmp/appsbx-url-browser.log 2>&1 < /dev/null &\n"
        "exit 0\n",
        encoding="utf-8",
    )
    os.chmod(path, 0o755)
    return path


def _display_executable() -> Path | None:
    """Return an installed Xvfb executable, without accepting a host display."""
    candidate = Path("/usr/bin/Xvfb")
    try:
        candidate = candidate.resolve(strict=True)
    except OSError:
        return None
    if not candidate.is_file() or not os.access(candidate, os.X_OK):
        return None
    return candidate


def _display_helper_source(path: Path) -> Path | None:
    """Validate one fixed helper executable without treating it as a library."""
    path = path.absolute()
    if not any(_within(path, root) for root in SYSTEM_EXECUTABLE_ROOTS):
        return None
    try:
        resolved = path.resolve(strict=True)
    except OSError:
        return None
    if not resolved.is_file() or not os.access(resolved, os.X_OK):
        return None
    approved = SYSTEM_EXECUTABLE_ROOTS + SYSTEM_LIBRARY_ROOTS
    return path if any(_within(resolved, root) for root in approved) else None


def _vnc_server_executable() -> Path:
    """Return the approved x11vnc executable, without accepting PATH tricks."""
    discovered = shutil.which("x11vnc")
    if discovered is None:
        raise ELFError("VNC display requires x11vnc, but it is not installed")
    source = _display_helper_source(Path(discovered))
    if source is None:
        raise ELFError("x11vnc must be an executable in an approved system directory")
    return source


def prepare_vnc_bundle(state_dir: Path) -> VNCBundle:
    """Stage x11vnc and its ELF closure into a dedicated private bundle.

    The bridge is launched in its own Bubblewrap instance with a private
    network namespace.  This deliberately avoids executing a host x11vnc
    binary with access to the host filesystem or network.
    """
    server = _vnc_server_executable()
    digest = hashlib.sha256(server.read_bytes()).hexdigest()[:20]
    bundle_root = state_dir / f"vnc-runtime-v{VNC_BUNDLE_VERSION}-{digest}"
    manifest = bundle_root / "manifest.json"
    server_relative = server.absolute().relative_to("/")
    if manifest.exists():
        try:
            data = json.loads(manifest.read_text(encoding="utf-8"))
            staged_server = bundle_root / server_relative
            if (
                data.get("version") == VNC_BUNDLE_VERSION
                and data.get("server_digest") == digest
                and staged_server.is_file()
            ):
                return VNCBundle(bundle_root, staged_server, int(data.get("staged_libraries", 0)))
        except (OSError, ValueError, TypeError):
            pass
        raise ELFError("VNC runtime bundle exists but its manifest is invalid")

    state_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    temporary = Path(tempfile.mkdtemp(prefix=f".vnc-runtime-{digest}-", dir=state_dir))
    staged: set[Path] = set()
    visited: set[Path] = set()
    queue = [server]
    # There is no application root in this closure.  _resolve_dependency only
    # accepts the server's own directory and fixed system library roots.
    empty_app_root = temporary / "no-app-root"
    try:
        _stage_host_path(server, temporary, staged, SYSTEM_EXECUTABLE_ROOTS + SYSTEM_LIBRARY_ROOTS)
        while queue:
            current = queue.pop().resolve()
            if current in visited:
                continue
            visited.add(current)
            info = read_elf_info(current)
            names = list(info.needed)
            if info.interpreter:
                names.append(info.interpreter)
            for name in names:
                dependency = _resolve_dependency(name, current, empty_app_root, info.search_paths)
                if dependency is None:
                    raise ELFError(f"unresolved VNC dependency: {name}")
                source, is_app_file = dependency
                if is_app_file:
                    raise ELFError("VNC dependency unexpectedly resolved from an application root")
                _stage_host_path(source, temporary, staged)
                queue.append(source)
        (temporary / "manifest.json").write_text(json.dumps({
            "version": VNC_BUNDLE_VERSION,
            "server_digest": digest,
            "staged_libraries": len(staged),
        }, sort_keys=True) + "\n", encoding="utf-8")
        os.replace(temporary, bundle_root)
    except Exception:
        shutil.rmtree(temporary, ignore_errors=True)
        raise
    return VNCBundle(bundle_root, bundle_root / server_relative, len(staged))


def _find_system_library(name: str) -> Path | None:
    """Find one named library below the fixed system library roots."""
    candidates: list[Path] = []
    for root in SYSTEM_LIBRARY_ROOTS:
        candidates.append(root / name)
        try:
            candidates.extend(root.glob(f"*/{name}"))
        except OSError:
            continue
    for candidate in candidates:
        try:
            resolved = candidate.resolve(strict=True)
        except OSError:
            continue
        if resolved.is_file() and any(_within(resolved, root) for root in SYSTEM_LIBRARY_ROOTS):
            return candidate
    return None


def _stage_resource_tree(
    source: Path,
    bundle_root: Path,
    allowed_roots: tuple[Path, ...],
) -> None:
    """Copy a fixed data tree while rejecting symlinks that escape it."""
    try:
        resolved = source.resolve(strict=True)
    except OSError as exc:
        raise ELFError(f"required display data is unavailable: {source}") from exc
    if not resolved.is_dir() or not any(_within(resolved, root) for root in allowed_roots):
        raise ELFError(f"display data is outside approved system roots: {source}")
    destination = bundle_root / resolved.relative_to("/")
    shutil.copytree(resolved, destination, symlinks=True, dirs_exist_ok=True)
    for root, directories, files in os.walk(resolved, followlinks=False):
        for name in (*directories, *files):
            item = Path(root) / name
            if item.is_symlink():
                try:
                    target = item.resolve(strict=True)
                except OSError as exc:
                    raise ELFError(f"display data contains a broken symlink: {item}") from exc
                if not any(_within(target, approved) for approved in allowed_roots):
                    raise ELFError(f"display data symlink leaves approved roots: {item}")


def _write_gpu_sysfs_view(bundle_root: Path, gpu_info: GpuInfo) -> None:
    """Create a static, GPU-only sysfs compatibility view.

    Mesa/libdrm follows DRM class/device symlinks and reads a handful of PCI
    attributes.  Binding those host symlinks into a new mount namespace turns
    them into broken or incorrectly rooted links.  Copy the small read-only
    metadata set instead, preserving the expected topology but never exposing
    the host's live sysfs, DMI, CPU, disk, or other PCI devices.
    """
    sys_devices = Path("/sys/devices")
    try:
        relative_device = gpu_info.sysfs_device.relative_to(sys_devices)
        relative_render = gpu_info.sysfs_render_node.relative_to(sys_devices)
    except ValueError as exc:
        raise ELFError("GPU sysfs device is outside /sys/devices") from exc
    if relative_render != relative_device / "drm" / gpu_info.render_node.name:
        raise ELFError("GPU sysfs render node is not below its selected device")

    def destination(path: Path) -> Path:
        # ``bundle_root/sys`` is the synthetic namespace's /sys root.
        return bundle_root / "sys" / path.relative_to("/sys")

    device_destination = destination(gpu_info.sysfs_device)
    device_destination.mkdir(parents=True, exist_ok=True, mode=0o755)
    # These values identify the selected GPU to Mesa.  They are intentionally
    # not a general PCI or motherboard inventory.
    for name in ("vendor", "device", "subsystem_vendor", "subsystem_device",
                 "revision", "class", "uevent", "modalias", "boot_vga"):
        source = gpu_info.sysfs_device / name
        if source.is_file():
            target = device_destination / name
            target.write_bytes(source.read_bytes()[:64 * 1024])
    # Mesa/libdrm uses the PCI config header while identifying the render
    # device. It is binary data, so expose only the first 64 bytes needed for
    # enumeration.
    config = gpu_info.sysfs_device / "config"
    if config.is_file():
        # Expose only the immutable identification portion of the PCI header.
        # BARs and the capability pointer are host address/topology data and
        # are not needed by Mesa for render-node identification.
        config_bytes = bytearray(config.read_bytes()[:64])
        if len(config_bytes) != 64:
            raise ELFError("selected GPU PCI config is shorter than 64 bytes")
        config_bytes[0x10:0x28] = b"\0" * (0x28 - 0x10)
        config_bytes[0x34] = 0
        target = device_destination / "config"
        target.write_bytes(config_bytes)
        target.chmod(0o444)
    else:
        raise ELFError("selected GPU PCI config is unavailable")
    (device_destination / "driver").symlink_to(
        "/sys/bus/pci/drivers/" + gpu_info.kernel_driver
    )
    (device_destination / "subsystem").symlink_to("/sys/bus/pci")

    render_destination = destination(gpu_info.sysfs_render_node)
    render_destination.mkdir(parents=True, exist_ok=True, mode=0o755)
    for name in ("dev", "uevent"):
        source = gpu_info.sysfs_render_node / name
        if source.is_file():
            (render_destination / name).write_bytes(source.read_bytes()[:64 * 1024])
    # Match the kernel sysfs topology. This resolves from the render node
    # directory back to the selected PCI device.
    (render_destination / "device").symlink_to("../../../" + gpu_info.sysfs_device.name)
    (render_destination / "subsystem").symlink_to("/sys/class/drm")
    class_destination = bundle_root / "sys" / "class" / "drm" / gpu_info.render_node.name
    class_destination.mkdir(parents=True, exist_ok=True, mode=0o755)
    for name in ("dev", "uevent"):
        source = gpu_info.sysfs_render_node / name
        if source.is_file():
            (class_destination / name).write_bytes(source.read_bytes()[:64 * 1024])
    # The DRM class entry points back to the single staged PCI device.
    (class_destination / "device").symlink_to("/sys/devices/" + str(relative_device))
    dev_destination = bundle_root / "sys" / "dev" / "char"
    dev_destination.mkdir(parents=True, exist_ok=True, mode=0o755)
    device_number = gpu_info.render_node.stat().st_rdev
    dev_node = dev_destination / f"{os.major(device_number)}:{os.minor(device_number)}"
    dev_node.mkdir(parents=True, exist_ok=True, mode=0o755)
    for name in ("dev", "uevent"):
        source = gpu_info.sysfs_render_node / name
        if source.is_file():
            (dev_node / name).write_bytes(source.read_bytes()[:64 * 1024])
    # The devchar entry itself is not mounted. runtime.py creates the
    # kernel-style symlink with bwrap --symlink.
    driver_destination = bundle_root / "sys" / "bus" / "pci" / "drivers" / gpu_info.kernel_driver
    driver_destination.mkdir(parents=True, exist_ok=True, mode=0o755)
    (driver_destination / gpu_info.sysfs_device.name).symlink_to(
        "/sys/devices/" + str(relative_device)
    )
    # libdrm/libudev uses this small device database record when resolving a
    # render node.  Generate only stable GPU topology fields; do not copy the
    # host udev database or its unrelated device records.
    device_number = gpu_info.render_node.stat().st_rdev
    udev_data = bundle_root / "run" / "udev" / "data"
    udev_data.mkdir(parents=True, exist_ok=True, mode=0o755)
    (udev_data / f"c{os.major(device_number)}:{os.minor(device_number)}").write_text(
        f"S:dri/by-path/pci-{gpu_info.sysfs_device.name}-render\\n"
        f"E:ID_PATH=pci-{gpu_info.sysfs_device.name}\\n"
        f"E:ID_PATH_TAG=pci-{gpu_info.sysfs_device.name.replace(':', '_').replace('.', '_')}\\n"
        f"E:ID_FOR_SEAT=drm-pci-{gpu_info.sysfs_device.name.replace(':', '_').replace('.', '_')}\\n"
        "G:seat\\nV:1\\n",
        encoding="ascii",
    )


def synthetic_df_script(disk_mb: int) -> str:
    """Return the private, deterministic ``df`` compatibility command.

    The sandbox cannot stage the host ``df`` binary: that command would
    inspect the Bubblewrap mount table and expose host-derived capacity or
    mount names.  Electron launchers commonly use ``df`` only to reject an
    installation when free space is insufficient, so provide a POSIX-shaped
    response with an explicitly configured synthetic capacity instead.
    """
    if isinstance(disk_mb, bool) or not isinstance(disk_mb, int) or not 1_024 <= disk_mb <= 1_048_576:
        raise ELFError("synthetic disk capacity must be an integer in [1024, 1048576] MiB")
    blocks = disk_mb * 1024
    return f"""#!/bin/sh
# Generated by appsbx. Do not invoke a host df binary from this sandbox.
case \"${{1-}}\" in
  --version)
    printf '%s\\n' 'df (appsbx synthetic) 1'
    exit 0
    ;;
  --help)
    printf '%s\\n' 'Usage: df [OPTION]... [FILE]...'
    exit 0
    ;;
esac
printf '%s\\n' 'Filesystem 1024-blocks Used Available Capacity Mounted on'
printf '%s\\n' 'appsbxfs {blocks} 0 {blocks} 0% /home/appsbx'
"""


def zaap_start_script() -> str:
    """Return Zaap's first-install game-launch compatibility command.

    Zaap falls back to the bare command ``zaap-start`` if its game
    configuration was read before a newly downloaded release had written
    ``zaap.yml``.  The official Linux release normally replaces that fallback
    with ``./dofus1electron``.  This private helper preserves the fallback's
    arguments but always executes that exact in-sandbox release binary; it
    cannot be used to execute a host command or resolve an application-supplied
    path.
    """
    return """#!/bin/sh
# Generated by appsbx.  Zaap's first-install fallback for Dofus Retro.
set -eu
game_root=/home/appsbx/.config/Ankama/Retro
game="$game_root/dofus1electron"
if [ ! -x "$game" ]; then
    echo 'appsbx: downloaded Dofus executable is unavailable' >&2
    exit 127
fi
cd "$game_root"
exec "$game" "$@"
"""


def _validate_url_broker_display(display_backend: str, url_broker: bool) -> None:
    """Keep authentication browsing inside a display-visible sandbox only."""
    if url_broker and display_backend not in {"xvfb", "host"}:
        raise ELFError("private URL broker requires a visible sandbox display backend")


def prepare_runtime_bundle(
    app_root: Path,
    app_command: Iterable[str],
    state_dir: Path,
    display_backend: str = "none",
    synthetic_disk_mb: int = 102_400,
    url_broker: bool = False,
    gpu_info: GpuInfo | None = None,
    trace_hardware: bool = False,
    shared_game_root: Path | None = None,
) -> RuntimeBundle:
    """Stage the executable closure and private compatibility helpers."""
    if display_backend not in {"none", "xvfb", "host"}:
        raise ELFError("display backend must be none, xvfb, or host")
    _validate_url_broker_display(display_backend, url_broker)
    if gpu_info is not None and display_backend != "host":
        raise ELFError("hardware GPU runtime requires the host display backend")
    df_script = synthetic_df_script(synthetic_disk_mb)
    app_root = app_root.resolve()
    entrypoint = _entrypoint(app_root, app_command)
    game_entry = _downloaded_game_entrypoint(state_dir, shared_game_root)
    payload_roots = [app_root]
    game_key = "nogame"
    if game_entry is not None:
        game_entrypoint, game_stamp = game_entry
        payload_roots.append(game_entrypoint.parent)
        game_key = f"game-{game_stamp}"
    display_executable = _display_executable() if display_backend == "xvfb" else None
    if display_backend == "xvfb" and display_executable is None:
        raise ELFError("display backend xvfb requested, but /usr/bin/Xvfb is not installed")
    browser_executable = _private_browser_source() if url_broker else None
    key = hashlib.sha256(entrypoint.read_bytes()).hexdigest()[:20]
    display_key = "xvfb" if display_executable else ("host" if display_backend == "host" else "nodisplay")
    gpu_key = f"gpu-{gpu_info.mesa_driver}" if gpu_info is not None else "gpu-none"
    broker_key = "browser" if browser_executable is not None else "nobrowser"
    trace_key = "trace" if trace_hardware else "notrace"
    bundle_root = state_dir / f"runtime-v{BUNDLE_VERSION}-{key}-{game_key}-{display_key}-{gpu_key}-{broker_key}-{trace_key}-disk{synthetic_disk_mb}"
    manifest = bundle_root / "manifest.json"
    if manifest.exists():
        try:
            data = json.loads(manifest.read_text(encoding="utf-8"))
            if (
                data.get("version") == BUNDLE_VERSION
                and data.get("entry_digest") == key
                and data.get("display_backend") == display_backend
                and data.get("synthetic_disk_mb") == synthetic_disk_mb
                and data.get("url_broker") == url_broker
                and data.get("gpu_driver") == (gpu_info.mesa_driver if gpu_info else None)
                and data.get("game_runtime") == game_key
                and data.get("trace_hardware") == trace_hardware
            ):
                script = bundle_root / "usr" / "bin" / "appsbx-xvfb-exec"
                if display_backend == "xvfb" and not script.is_file():
                    raise ELFError("runtime bundle exists but its Xvfb helper is missing")
                if not (bundle_root / "usr" / "bin" / "df").is_file():
                    raise ELFError("runtime bundle exists but its synthetic df helper is missing")
                if not (bundle_root / "usr" / "bin" / "zaap-start").is_file():
                    raise ELFError("runtime bundle exists but its Zaap game-launch helper is missing")
                if trace_hardware and not (bundle_root / "usr" / "bin" / "appsbx-trace").is_file():
                    raise ELFError("runtime bundle exists but its hardware trace helper is missing")
                staged_browser = None
                if browser_executable is not None:
                    staged_browser = bundle_root / browser_executable.relative_to("/")
                    if not staged_browser.is_file() or not (bundle_root / "usr" / "bin" / "xdg-open").is_file():
                        raise ELFError("runtime bundle exists but its private URL broker is missing")
                return RuntimeBundle(
                    bundle_root,
                    entrypoint,
                    int(data.get("staged_libraries", 0)),
                    script if display_backend == "xvfb" and script.is_file() else None,
                    staged_browser,
                )
        except (OSError, ValueError, TypeError):
            pass
        raise ELFError("runtime bundle exists but its manifest is invalid")

    state_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    temporary = Path(tempfile.mkdtemp(prefix=f".runtime-{key}-", dir=state_dir))
    staged: set[Path] = set()
    visited: set[Path] = set()
    queue = [entrypoint]
    if game_entry is not None:
        queue.append(game_entry[0])
    helpers: list[Path] = []
    try:
        # This small library installs a seccomp user-notification filter only
        # after bwrap has finished its own setup and execs the application.
        # It therefore cannot affect bwrap, while every payload child inherits
        # the direct-syscall guard.
        try:
            build_guard(temporary)
        except SyscallGuardError as exc:
            raise ELFError(str(exc)) from exc
        # Electron's Linux protocol-registration path launches xdg-settings
        # before the application reaches its own setup.  Stage /bin/sh for the
        # private compatibility helper below; it is still resolved and staged
        # through the normal ELF dependency closure.
        shell = Path("/bin/sh")
        shell_source = _display_helper_source(shell)
        if shell_source is None:
            raise ELFError(f"required runtime helper is unavailable: {shell}")
        _stage_host_path(shell_source, temporary, staged, SYSTEM_EXECUTABLE_ROOTS + SYSTEM_LIBRARY_ROOTS)
        queue.append(shell_source)
        if game_entry is not None:
            # Observed from the official Dofus startup path: it uses grep in
            # a small shell probe. Stage precisely that standard utility and
            # its ELF closure instead of exposing a general host /usr/bin.
            grep = Path("/usr/bin/grep")
            grep_source = _display_helper_source(grep)
            if grep_source is None:
                raise ELFError(f"required Dofus compatibility helper is unavailable: {grep}")
            _stage_host_path(grep_source, temporary, staged, SYSTEM_EXECUTABLE_ROOTS + SYSTEM_LIBRARY_ROOTS)
            queue.append(grep_source)
        if trace_hardware:
            # This diagnostic tool is staged only on explicit request. It
            # runs inside the sandbox after privileged network setup, rather
            # than ptracing sudo/the controller from outside.
            for helper in (Path("/usr/bin/env"), Path("/usr/bin/strace")):
                source = _display_helper_source(helper)
                if source is None:
                    raise ELFError(f"hardware trace helper is unavailable: {helper}")
                _stage_host_path(source, temporary, staged, SYSTEM_EXECUTABLE_ROOTS + SYSTEM_LIBRARY_ROOTS)
                queue.append(source)
            trace_script = temporary / "usr" / "bin" / "appsbx-trace"
            trace_script.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
            trace_script.write_text(
                "#!/bin/sh\n"
                "exec /usr/bin/strace -ff -tt -s 256 "
                "-e trace=uname,sysinfo,sched_getaffinity,openat,openat2,readlink,readlinkat,statx,access,ioctl "
                "-o /home/appsbx/hardware-trace "
                "-E LD_PRELOAD=/usr/lib/appsbx/libappsbx-syscall-guard.so -- \"$@\"\n",
                encoding="utf-8",
            )
            os.chmod(trace_script, 0o755)
        # Chromium/NSS loads these cryptographic modules at runtime rather
        # than declaring them in Electron's direct DT_NEEDED closure. The
        # network stack can therefore start successfully and then abort while
        # initializing its certificate database if they are absent. Stage the
        # fixed system copies and their ELF closures; never fall back to a
        # host /usr or /lib mount.
        for library_name in (
            "libsoftokn3.so", "libfreebl3.so", "libfreeblpriv3.so",
            "libnssdbm3.so", "libnssckbi.so",
        ):
            library = _find_system_library(library_name)
            if library is None:
                raise ELFError(f"required NSS runtime module is unavailable: {library_name}")
            _stage_host_path(library, temporary, staged)
            queue.append(library)
        if display_executable is not None or display_backend == "host":
            # Xvfb is launched inside the same bubblewrap root.  The shell and
            # helper tools are staged explicitly because the sandbox does not
            # mount the host /bin or /usr wholesale.
            helpers = ([display_executable] if display_executable is not None else []) + [
                Path("/usr/bin/sleep"),
                Path("/usr/bin/cat"), Path("/usr/bin/mkdir"),
                Path("/usr/bin/chmod"), Path("/usr/bin/setpriv"),
                Path("/usr/bin/xkbcomp"), Path("/usr/bin/head"),
                Path("/usr/bin/hostname"),
            ]
            for helper in helpers:
                candidate = _display_helper_source(helper)
                if candidate is None:
                    raise ELFError(f"display helper is outside approved system roots: {helper}")
                _stage_host_path(helper, temporary, staged, SYSTEM_EXECUTABLE_ROOTS + SYSTEM_LIBRARY_ROOTS)
            # Electron loads this through dlopen after the main ELF closure has
            # been staged.  Keep the dependency explicit and fail closed rather
            # than allowing a fallback to a host /usr or /lib mount.
            # Electron's GPU/media code loads these optional libraries with
            # dlopen(), so they are not present in the executable's DT_NEEDED
            # closure.  Stage only fixed system copies; do not expose the
            # host's /usr/lib or device tree as a fallback.
            for library_name in (
                "libX11-xcb.so.1", "libudev.so.1", "libva.so.2",
                "libva-x11.so.2", "libva-drm.so.2",
                "libdrm.so.2", "libEGL.so.1", "libGL.so.1", "libGLX.so.0",
                "libEGL_mesa.so.0", "libGLX_mesa.so.0", "libGLESv2.so.2",
                "libOpenGL.so.0", "libGLdispatch.so.0",
                "libgbm.so.1", "libvulkan.so.1",
            ):
                library = _find_system_library(library_name)
                if library is None:
                    raise ELFError(f"required display library is unavailable: {library_name}")
                _stage_host_path(library, temporary, staged)
                queue.append(library)
            if gpu_info is not None:
                _stage_host_path(gpu_info.driver_library, temporary, staged)
                queue.append(gpu_info.driver_library)
                # Xwayland's GLX path may request the legacy Intel DRI name
                # even when EGL/Mesa maps i915 to iris. Keep the alias in the
                # private bundle; do not expose the host DRI directory.
                if gpu_info.kernel_driver == "i915":
                    legacy_intel = gpu_info.driver_library.with_name("i915_dri.so")
                    if legacy_intel.is_file():
                        _stage_host_path(legacy_intel, temporary, staged)
                        queue.append(legacy_intel)
                # GTK/Electron may load GDK-pixbuf modules after startup.
                # Keep the loader cache and modules inside the private
                # runtime; never allow a host /usr/lib fallback.
                pixbuf = _find_system_library("libgdk_pixbuf-2.0.so.0")
                if pixbuf is not None:
                    _stage_host_path(pixbuf, temporary, staged)
                    queue.append(pixbuf)
                else:
                    raise ELFError("required GTK runtime library is unavailable: libgdk_pixbuf-2.0.so.0")
                pixbuf_dir = Path("/usr/lib/x86_64-linux-gnu/gdk-pixbuf-2.0/2.10.0")
                pixbuf_loaders = pixbuf_dir / "loaders"
                if pixbuf_loaders.is_dir():
                    _stage_resource_tree(pixbuf_loaders, temporary, SYSTEM_LIBRARY_ROOTS)
                pixbuf_cache = pixbuf_dir / "loaders.cache"
                if pixbuf_cache.is_file():
                    _stage_regular_file(pixbuf_cache, temporary, SYSTEM_LIBRARY_ROOTS)
            resource_roots = (Path("/usr/share/X11"), Path("/usr/share/fonts"))
            _stage_resource_tree(Path("/usr/share/X11/xkb"), temporary, resource_roots)
            for resource in (Path("/usr/share/X11/locale"), Path("/usr/share/fonts/X11/misc")):
                if resource.is_dir():
                    _stage_resource_tree(resource, temporary, resource_roots)
            # Chromium's native font initialization requires a scalable
            # default sans font.  The host trace showed DejaVuSans.ttf being
            # opened; bitmap X11 fonts alone are insufficient and can trigger
            # a native fatal path in this Electron build.
            dejavu = Path("/usr/share/fonts/truetype/dejavu")
            if dejavu.is_dir():
                _stage_resource_tree(dejavu, temporary, resource_roots)
            # GLib consults these fixed, non-identity resources during
            # Electron startup.  Stage them explicitly instead of exposing
            # the host's /usr/share tree.
            data_roots = (Path("/usr/share/glib-2.0"), Path("/usr/share/locale"), Path("/etc"))
            for resource in (
                Path("/usr/share/glib-2.0/schemas"),
                Path("/usr/share/locale/locale.alias"),
            ):
                if resource.is_dir():
                    _stage_resource_tree(resource, temporary, data_roots)
                elif resource.is_file():
                    _stage_regular_file(resource, temporary, data_roots)
            # Native Wayland/GTK initialization asks GDK-pixbuf to load its
            # standard missing-image icon.  This small fixed icon subset is
            # data-only and does not expose the host desktop or credentials.
            adwaita_status = Path("/usr/share/icons/Adwaita/48x48/status")
            if adwaita_status.is_dir():
                _stage_resource_tree(adwaita_status, temporary, (Path("/usr/share/icons"),))
            queue.extend(helpers)
        if gpu_info is not None:
            _write_gpu_sysfs_view(temporary, gpu_info)
        _write_private_xdg_settings(temporary)
        staged_browser = None
        if browser_executable is not None:
            # Copy the browser package as data first.  Its local resources and
            # shared objects remain under the exact private /opt path expected
            # by Chromium; system dependencies are resolved below and staged
            # individually from approved library roots.
            _stage_resource_tree(GOOGLE_CHROME_ROOT, temporary, (GOOGLE_CHROME_ROOT,))
            browser_queue = [browser_executable]
            browser_visited: set[Path] = set()
            while browser_queue:
                current = browser_queue.pop().resolve()
                if current in browser_visited:
                    continue
                browser_visited.add(current)
                info = read_elf_info(current)
                names = list(info.needed)
                if info.interpreter:
                    names.append(info.interpreter)
                for name in names:
                    dependency = _resolve_dependency(name, current, (GOOGLE_CHROME_ROOT,), info.search_paths)
                    if dependency is None:
                        raise ELFError(f"unresolved private-browser dependency: {name}")
                    source, is_browser_file = dependency
                    if not is_browser_file:
                        _stage_host_path(source, temporary, staged)
                    browser_queue.append(source)
            staged_browser = temporary / browser_executable.relative_to("/")
            _write_private_xdg_open(temporary, browser_executable)
        df_helper = temporary / "usr" / "bin" / "df"
        df_helper.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
        df_helper.write_text(df_script, encoding="utf-8")
        os.chmod(df_helper, 0o755)
        game_launcher = temporary / "usr" / "bin" / "zaap-start"
        game_launcher.write_text(zaap_start_script(), encoding="utf-8")
        os.chmod(game_launcher, 0o755)
        while queue:
            current = queue.pop()
            current = current.resolve()
            if current in visited:
                continue
            visited.add(current)
            info = read_elf_info(current)
            names = list(info.needed)
            if info.interpreter:
                names.append(info.interpreter)
            for name in names:
                dependency = _resolve_dependency(name, current, payload_roots, info.search_paths)
                if dependency is None:
                    raise ELFError(f"unresolved ELF dependency: {name}")
                source, is_app_file = dependency
                if not is_app_file:
                    _stage_host_path(source, temporary, staged)
                queue.append(source)
        fonts_config = temporary / "etc" / "appsbx-fonts.conf"
        fonts_config.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
        fonts_config.write_text(MINIMAL_FONTCONFIG, encoding="utf-8")
        alsa_config = temporary / "etc" / "appsbx-alsa.conf"
        alsa_config.write_text(MINIMAL_ALSA, encoding="utf-8")
        display_script = None
        if display_executable is not None:
            display_script = temporary / "usr" / "bin" / "appsbx-xvfb-exec"
            display_script.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
            display_script.write_text(
                """#!/bin/sh
set -eu
display="${APPSBX_X_DISPLAY:-:99}"
case "$display" in
    :[0-9]*) display_number="${display#:}" ;;
    *) echo 'appsbx: invalid private X display' >&2; exit 112 ;;
esac
log=/tmp/appsbx-xvfb.log
mkdir -p /tmp/.X11-unix
chmod 0700 /tmp/.X11-unix
/usr/bin/Xvfb "$display" -screen 0 1280x720x24 -nolisten tcp -ac -noreset -terminate >"$log" 2>&1 &
server=$!
cleanup() {
    kill "$server" 2>/dev/null || true
    wait "$server" 2>/dev/null || true
}
trap cleanup EXIT HUP INT TERM
i=0
while [ "$i" -lt 100 ]; do
    if [ -S "/tmp/.X11-unix/X${display_number}" ]; then
        export DISPLAY="$display"
        exec /usr/bin/setpriv \
            --nnp \
            --bounding-set=-all --inh-caps=-all \
            --ambient-caps=-all -- "$@"
    fi
    if ! kill -0 "$server" 2>/dev/null; then
        cat "$log" >&2 || true
        exit 111
    fi
    i=$((i + 1))
    /usr/bin/sleep 0.05
done
cat "$log" >&2 || true
exit 111
""",
                encoding="utf-8",
            )
            os.chmod(display_script, 0o755)
        (temporary / "manifest.json").write_text(json.dumps({
            "version": BUNDLE_VERSION,
            "entry_digest": key,
            "staged_libraries": len(staged),
            "display_backend": display_backend,
            "synthetic_disk_mb": synthetic_disk_mb,
            "url_broker": url_broker,
            "gpu_driver": gpu_info.mesa_driver if gpu_info else None,
            "game_runtime": game_key,
            "trace_hardware": trace_hardware,
        }, sort_keys=True) + "\n", encoding="utf-8")
        os.replace(temporary, bundle_root)
    except Exception:
        shutil.rmtree(temporary, ignore_errors=True)
        raise
    # ``temporary`` is atomically renamed to ``bundle_root`` above. Do not
    # return the pre-rename path for the Xvfb wrapper: callers validate and
    # execute the published bundle path immediately after this function.
    published_display_script = (
        bundle_root / "usr" / "bin" / "appsbx-xvfb-exec"
        if display_script is not None else None
    )
    published_browser = (
        bundle_root / browser_executable.relative_to("/")
        if browser_executable is not None else None
    )
    return RuntimeBundle(bundle_root, entrypoint, len(staged), published_display_script, published_browser)
